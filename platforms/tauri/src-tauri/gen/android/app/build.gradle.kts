val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Release signing: the key lives OUTSIDE the repo (see platforms/tauri/README.md).
//   CI: NOTEMAKER_ANDROID_KEYSTORE (path), NOTEMAKER_ANDROID_KEYSTORE_PASSWORD, NOTEMAKER_ANDROID_KEY_ALIAS,
//       NOTEMAKER_ANDROID_KEY_PASSWORD (from GitHub Actions secrets).
//   Local: the same variables, or gen/android/keystore.properties (git-ignored) with storeFile, storePassword,
//       keyAlias, keyPassword. Without either, release builds are unsigned; debug builds use the debug key.
val keystoreProperties = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? = System.getenv(env)?.takeIf { it.isNotEmpty() } ?: keystoreProperties.getProperty(prop)
val releaseStoreFile = signingValue("storeFile", "NOTEMAKER_ANDROID_KEYSTORE")

android {
    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = file(releaseStoreFile)
                storePassword = signingValue("storePassword", "NOTEMAKER_ANDROID_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "NOTEMAKER_ANDROID_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "NOTEMAKER_ANDROID_KEY_PASSWORD")
            }
        }
    }
    compileSdk = 36
    namespace = "com.mth.notemaker"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "com.mth.notemaker"
        minSdk = 24
        targetSdk = 36
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            if (releaseStoreFile != null) signingConfig = signingConfigs.getByName("release")
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

