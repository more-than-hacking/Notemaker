#!/bin/bash
# Copy the web UI into an app bundle's Resources and generate the integrity data.
#   tools/bundle-web.sh <Contents/Resources dir> <output BuildIntegrity.swift>
# Writes:
#   <Resources>/web/…                 index.html, app.js, styles.css, manifest.webmanifest, js/, web-icons/
#   <Resources>/web-manifest.json     { version, algorithm: "sha256", files: { relpath: sha256 } }
#   <output .swift>                   enum BuildIntegrity { static let manifestSHA256 = "<sha256 of web-manifest.json>" }
# The app verifies all of this at launch (Notemaker/Core/WebIntegrity.swift).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RES="$1"
GEN="$2"

rm -rf "$RES/web"
mkdir -p "$RES/web" "$(dirname "$GEN")"
for f in index.html app.js styles.css manifest.webmanifest; do
  [ -f "$ROOT/$f" ] && cp "$ROOT/$f" "$RES/web/"
done
for d in js web-icons; do
  [ -d "$ROOT/$d" ] && cp -RL "$ROOT/$d" "$RES/web/"      # -L: never ship symlinks (they'd fail the check)
done
find "$RES/web" -name .DS_Store -delete
[ -f "$RES/web/index.html" ] || { echo "❌ index.html missing" >&2; exit 1; }

/usr/bin/python3 -I - "$RES/web" "$RES/web-manifest.json" <<'PY'
import hashlib, json, os, sys
web, out = sys.argv[1], sys.argv[2]
files = {}
for d, dirs, names in os.walk(web):
    dirs.sort()
    for n in sorted(names):
        if n == ".DS_Store":
            continue
        p = os.path.join(d, n)
        with open(p, "rb") as fh:
            files[os.path.relpath(p, web).replace(os.sep, "/")] = hashlib.sha256(fh.read()).hexdigest()
with open(out, "w", encoding="utf-8") as fh:
    json.dump({"version": 1, "algorithm": "sha256", "files": files}, fh, indent=2, sort_keys=True)
    fh.write("\n")
PY

SHA=$(shasum -a 256 "$RES/web-manifest.json" | awk '{print $1}')
cat > "$GEN" <<SWIFT
// Generated by tools/bundle-web.sh — do not edit.
enum BuildIntegrity {
    /// SHA-256 of Contents/Resources/web-manifest.json at build time.
    static let manifestSHA256 = "$SHA"
}
SWIFT
echo "→ Web UI bundled: $(python3 -I -c 'import json,sys;print(len(json.load(open(sys.argv[1]))["files"]))' "$RES/web-manifest.json") files, manifest sha256 ${SHA:0:16}…"
